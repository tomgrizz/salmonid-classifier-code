"""In plain terms: this is the project's shared "settings" file. It tells every other
script in the repository where to find things on disk (the data files, the trained model,
and the raw underwater camera footage) and it lists the fixed facts of the study — the five
fish species and the numeric rules used to count them and decide if a fish is moving
upstream. It produces no number or figure of its own, but every result and figure in the
paper is generated by scripts that read their file locations and species list from here.

Central path and constant resolver.

Every module imports its file locations and study constants from here, so no other file
contains a drive letter or a folder name. To run on your machine you change nothing in the
code: you either place downloads under ``external/`` or set a few environment variables.

Where each path comes from, in order
-------------------------------------
1. An environment variable (for example ``SALMONID_PROJECTS_ROOT``).
2. The same name in an optional ``.env`` file at the repository root (copy ``.env.example``).
3. A default inside the repository: ``external/<name>``. That folder is git-ignored and
   empty in a fresh clone. A script that needs something from it stops with one sentence
   saying what is missing and which variable locates it (``require()`` below).

Two tiers of input
------------------
* **Tier 1: committed in ``data/``.** Small published tables: the held-out test set and the
  model's answers for it, the daily and seasonal counts, the count tables under each
  candidate direction rule, and the per-video tables behind the remaining statistics. These
  are always present, so the classification score, the agreement statistics and every figure
  drawn from counts recompute on a fresh clone with no configuration (``python run_tier1.py``).
* **Tier 2: external.** Too large or not ours to redistribute: the 819 MB model weights, the
  training images, the stored detections, the raw fishway video, and the technicians'
  review records. ``docs/DATA_AVAILABILITY.md`` says what each is and how to obtain it.

Species and class numbers
-------------------------
The model outputs six classes: ``0 Chinook, 1 Coho, 2 Atlantic, 3 Rainbow Trout,
4 Brown Trout, 5 Small Salmonid``. The manuscript reports the first five. "Small Salmonid"
is a catch-all for juvenile fish that the model detects but that is not part of the reported
counts and never appears in the technician record. ``SPECIES`` is therefore the five-species
list used for every count and score; ``NUM_DETECT_CLASSES`` is 6.
"""
