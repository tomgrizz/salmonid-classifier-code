"""In plain terms: this is the project's shared "settings" file. It tells every other
script in the repository where to find things on disk (the data files, the trained model,
and the raw underwater camera footage) and it lists the fixed facts of the study — the five
fish species and the numeric rules used to count them and decide if a fish is moving
upstream. It produces no number or figure of its own, but every result and figure in the
paper is generated by scripts that read their file locations and species list from here.

Central path + constant resolver for the salmonid-classifier-code repository.

Every module in this package imports its filesystem locations and domain constants from
here instead of hard-coding drive letters (``G:/``, ``F:/`` ...). This is the single change
we make to the analysis code relative to the working research repo: **logic is untouched,
only paths are centralised**, so the code that produced the manuscript numbers is preserved
verbatim while still running on a reviewer's machine.

Resolution order for every path
-------------------------------
1. An environment variable (e.g. ``SALMONID_PROJECTS_ROOT``) — set these to point at data
   you have downloaded.
2. A key in an optional ``.env`` file at the repository root (see ``.env.example``).
3. A *faithful default* — the absolute path the artifact lived at on the original OMNRF
   workstation. These defaults let the original author re-run unchanged; on any other
   machine they simply won't exist and you must set the env var (the scripts fail loudly
   with a clear message rather than silently mis-reading).

Two data tiers
--------------
* **Committed, repo-local (``data/``)** — small published artifacts: the frozen held-out
  test set, its predictions, the canonical daily/summary results, the net-rule sweeps, the
  2024 held-out net. These resolve *inside the repo* by default, so every figure, the
  concordance statistics, and the headline held-out score reproduce on a fresh clone with
  **zero configuration** (see ``README.md`` "Tier 1").
* **External downloads** — large artifacts that cannot live in git: the 819 MB model
  checkpoint, the frozen training COCO, the corpus detect-stores, and the raw tunnel-camera
  footage. Point at them with the ``SALMONID_*`` env vars; see ``docs/DATA_AVAILABILITY.md``.

Species / class convention
---------------------------
The detector emits 6 classes: ``0 Chinook · 1 Coho · 2 Atlantic · 3 Rainbow Trout ·
4 Brown Trout · 5 Small Salmonid``. The manuscript reports the **five** salmonid species;
"Small Salmonid" is a catch-all the model detects but that is excluded from the official
OMNRF report, and it never appears in the technician ground truth. ``SPECIES`` below is
therefore the 5-species list used for every count / score; ``NUM_DETECT_CLASSES`` is 6.
"""
