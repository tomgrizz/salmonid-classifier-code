def _load_dotenv(path: Path) -> None:
    """Populate os.environ from a simple KEY=VALUE .env file (existing env wins)."""
    if not path.is_file():
        return
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, val = line.partition("=")
        key, val = key.strip(), val.strip().strip('"').strip("'")
        os.environ.setdefault(key, val)


_load_dotenv(REPO_ROOT / ".env")


def env_path(name: str, default: str | Path) -> Path:
    """Return Path from env var ``name`` if set, else the faithful ``default``."""
    return Path(os.environ.get(name, str(default)))


def require(path: str | Path, what: str, env_var: str | None = None) -> Path:
    """Return ``path`` if it exists, else stop with a message that says what is missing.

    Tier-2 scripts call this on every external input (weights, footage, detect-stores) so a
    reader on another machine gets one clear sentence instead of a traceback from deep inside
    a library. ``what`` is a plain description; ``env_var`` names the setting that relocates it.
    """
    p = Path(path)
    if p.exists():
        return p
    hint = (f" Set {env_var} (see .env.example) to where you downloaded it." if env_var else "")
    raise SystemExit(
        f"Missing external input: {what}\n  expected at: {p}\n"
        f"  This is a Tier-2 artifact that is not stored in git.{hint}\n"
        f"  See docs/DATA_AVAILABILITY.md for what it is and where to obtain it.")


